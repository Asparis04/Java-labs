    private void jButton1ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton1ActionPerformed
       try {
    double x = Double.parseDouble(txtX.getText().trim());
    double a = Double.parseDouble(txtA.getText().trim());
    double b = Double.parseDouble(txtB.getText().trim());

    if (b <= 0) {
        javax.swing.JOptionPane.showMessageDialog(this, 
                "Қате: B мәні 0-ден үлкен болуы керек!", 
                "Математикалық қате", 
                javax.swing.JOptionPane.WARNING_MESSAGE);
        return;
    }

    if (x < 0) {
        javax.swing.JOptionPane.showMessageDialog(this, 
                "Қате: X мәні теріс болмауы керек (X >= 0)!", 
                "Математикалық қате", 
                javax.swing.JOptionPane.WARNING_MESSAGE);
        return;
    }

    double y = (Math.sqrt(x) + a) / b;
    lblResult.setText(String.format("Нәтиже Y = %.3f", y));

} catch (NumberFormatException ex) {
    javax.swing.JOptionPane.showMessageDialog(this, 
            "Қате: Тек сандарды енгізіңіз!", 
            "Енгізу қатесі", 
            javax.swing.JOptionPane.ERROR_MESSAGE);
}
    

   
    }//GEN-LAST:event_jButton1ActionPerformed

